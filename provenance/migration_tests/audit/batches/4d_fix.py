#!/usr/bin/env python3
"""Batch 4d fixes: package text that cites repo paths which now live in ViralScan-reproducibility or moved inside the package."""
import pathlib, re

PFX = "ViralScan-reproducibility/"
read = lambda p: pathlib.Path(p).read_text()
write = lambda p, s: pathlib.Path(p).write_text(s)

def sub1(path, old, new):
    t = read(path); assert old in t, (path, old); write(path, t.replace(old, new))

def prefix(path, pattern):
    t = read(path)
    new = re.sub(r"(?<![\w/-])(" + pattern + r")", PFX + r"\1", t)
    assert new != t, (path, pattern); write(path, new)

# schema copies: the top-level schemas/ directory is gone (4a); the package copy is the only one
sub1("docs/release_policy.md", "`schemas/v3/reference_manifest.schema.json`", "`src/viralscan/schemas/v3/reference_manifest.schema.json`")
sub1("docs/reference_maintenance.md", "Schema JSON files under `schemas/`", "Schema JSON files under `src/viralscan/schemas/`")

# experiment-repo paths
sub1("docs/panel_integrity.md", "`scripts/ref13_normaliser_qc.py`", "`ViralScan-reproducibility/scripts/ref13_normaliser_qc.py`")
for path in ("docs/output_reference.md", "src/viralscan/evidence_tiers.py", "src/viralscan/constants.py", "extras/build_gene_programs.py"):
    prefix(path, r"analysis/(?:v3_validation|audit_2026-10)/[\w./-]+")
t = read("docs/workflow_comparison.md")
new = t.replace("GENERATED by scripts/gen_workflow_comparison.py from analysis/v3_validation/protocol.yaml", "GENERATED by ViralScan-reproducibility/scripts/gen_workflow_comparison.py from ViralScan-reproducibility/analysis/v3_validation/protocol.yaml")
assert new != t; write("docs/workflow_comparison.md", new)

# PLAN row
sub1("PLAN.md", "reproducibility repo. Next: 4d (root clutter, doc relinks).", "reproducibility repo. Batch 4d (this change): package text that cited moved repo paths now names\n  ViralScan-reproducibility or the in-package schema copy. `ENVIRONMENTS_INSTALLATIONS.md` stays until its\n  deletion is approved. Next: local compatibility symlinks, then the repo-split row closes.")
