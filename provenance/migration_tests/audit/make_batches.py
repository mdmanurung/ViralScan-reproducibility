#!/usr/bin/env python3
"""Split moved_paths.txt into batches 4a-4d (explicit file lists) with a dependency-closed rule:
a moved test goes in the EARLIEST batch of anything it references (a tree path, a script, or a moved fixture).
usage: make_batches.py <outdir with moved_paths.txt, delete_paths.txt> <git ref>"""
import re, sys, pathlib, subprocess, collections
A = pathlib.Path(__file__).parent; out = pathlib.Path(sys.argv[1]); ref = sys.argv[2]
REPO = "/exports/archive/hg-funcgenom-research/mdmanurung/ViralScan"
moved = [l.strip() for l in open(out / "moved_paths.txt") if l.strip()]
deleted = [l.strip() for l in open(out / "delete_paths.txt") if l.strip()]
show = lambda p: subprocess.run(["git", "-C", REPO, "show", f"{ref}:{p}"], capture_output=True, text=True, errors="ignore").stdout
GOV = set("validate_claim_registry validate_artifact_inventory validate_v3_protocol validate_protocol_lock check_ledger_append_only check_g3_diff gen_workflow_comparison explore_ledger adjudicate_candidates generate_truth_panel v3_score v3_partition v3_lod val08_golden plant_anello_10x".split())
TREES = ("analysis/", "results/", "covid_viralscan/", "benchmark_inputs/", "claims/", "audits/", "todo/", "data/", "ref/")
ROOT_REPRO = {"reference_manifest.json", "reference_audit.tsv", "BENCHMARK_COMPARISON.md", "PROGRESS.md", "config/large_file_allowlist.txt"}
batch = {}
for p in moved:
    stem = pathlib.PurePosixPath(p).stem
    if p.startswith(TREES) or p in ROOT_REPRO: batch[p] = "4a"
    elif p.startswith("scripts/"): batch[p] = "4a" if stem in GOV else "4b"
    elif p.startswith("extras/"): batch[p] = "4b"
    elif p.startswith("docs/"): batch[p] = "4c"
    elif p.startswith("tests/"): batch[p] = None   # decided below
    else: batch[p] = "4b"
for d in deleted: batch[d] = "4d" if d == "ENVIRONMENTS_INSTALLATIONS.md" else "4a"   # schemas/ etc. go with 4a fixes
order = {"4a": 0, "4b": 1, "4c": 2, "4d": 3}
scripts = {pathlib.PurePosixPath(p).stem: p for p in moved if p.startswith("scripts/")}
trees = [p for p in moved if p.startswith(TREES)]
for p in [p for p, b in batch.items() if b is None]:
    t = show(p); best = "4b"; why = "no 4a reference"
    for stem, sp in scripts.items():
        if batch[sp] == "4a" and re.search(r"\b" + re.escape(stem) + r"\b", t): best, why = "4a", f"uses {stem}"; break
    if best != "4a" and re.search(r"(analysis|claims|results|covid_viralscan|benchmark_inputs|audits|todo)/[A-Za-z0-9_.-]+|schemas/v3|analysis\b", t) and re.search(r"(analysis|claims|covid_viralscan|benchmark_inputs|audits)/|[\"'](analysis|claims|covid_viralscan|benchmark_inputs|audits)[\"']", t):
        best, why = "4a", "reads a moved tree"
    batch[p] = best
(A / "batches").mkdir(exist_ok=True)
by = collections.defaultdict(list)
for p, b in batch.items(): by[b].append(p)
for b in ("4a", "4b", "4c", "4d"):
    (A / "batches" / f"{b}.rm").write_text("# generated by make_batches.py; explicit files only\n" + "\n".join(sorted(by[b])) + "\n")
    print(b, len(by[b]), collections.Counter(p.split("/")[0] for p in by[b]).most_common(5))
